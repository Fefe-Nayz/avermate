function titleCase(value: string): string {
  const spaced = value
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[-_.]+/g, " ")
    .trim();
  return spaced.length === 0
    ? value
    : `${spaced[0]?.toUpperCase() ?? ""}${spaced.slice(1)}`;
}

/** Turns stable core message keys into readable native copy. */
export function widgetMessage(key: string): string {
  // Dynamic provider labels are already user-facing names, not message keys.
  if (!key.startsWith("widget.")) return key;
  const measure = /^widget\.measure\.([^.]+)$/.exec(key)?.[1];
  if (measure && measure !== "formula") {
    return metricLabel(measure as CardMetric);
  }
  const description = /^widget\.measure\.([^.]+)\.description$/.exec(key)?.[1];
  if (description && description !== "formula") {
    return (
      metricHint(description as CardMetric) ??
      metricLabel(description as CardMetric)
    );
  }
  if (key.startsWith("widget.error.")) {
    return t(WIDGET_MESSAGE_LABELS[key] ?? "Check this value");
  }
  if (key.endsWith(".description")) return "";
  return t(
    WIDGET_MESSAGE_LABELS[key] ?? titleCase(key.split(".").at(-1) ?? key),
  );
}
